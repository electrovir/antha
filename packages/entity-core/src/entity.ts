import {assert, check} from '@augment-vir/assert';
import {
    makeWritable,
    mapObjectValues,
    type AnyObject,
    type Constructor,
    type EmptyObject,
    type IsNever,
    type MaybePromise,
    type Writable,
} from '@augment-vir/common';
import {assertValidShape, type Shape} from 'object-shape-tester';
import {defineTypedCustomEvent} from 'typed-event-target';
